"""Running a poison suite against a pipeline, without Vectraudit ever writing to it.

Two kinds of candidate can run poisoned:

- the built-in hybrid baseline loads the suite's ``poison-corpus.jsonl`` in memory beside
  its own corpus (``adapter.corpus_overlay``); a repeated document ID is an error;
- any Python or HTTP pipeline runs against a **staging** index into which *you* loaded the
  poisoned documents. Vectraudit inserts nothing. The candidate declares
  ``"environment": "staging"`` and ``"overlay": "suite/poison-suite.json"``, and a run
  without both is refused, so an unpoisoned or production index is never mistaken for a
  poisoned one.

The suite is checked before use: its descriptor must match the files beside it by hash, its
hash must be the one in its dataset's header, and so on. After a run, :func:`overlay_visibility`
asks whether any poisoned document appears in any recorded stage of any target question. If
none does, the overlay may not have been loaded into what was run. That is a warning, not
proof: a poisoned document that ranks nowhere looks the same, and an undisclosed stage
cannot be seen.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from vectraudit.evaluation.dataset import load_dataset
from vectraudit.pipelines.manifest import Candidate
from vectraudit.pipelines.poison import SUITE_FORMAT, SUITE_FORMAT_VERSION


class PoisonRunError(ValueError):
    """The suite or candidate cannot be used for a poison run; the message says why."""


@dataclass(frozen=True)
class Suite:
    """A verified poison suite."""

    root: Path
    descriptor: dict[str, Any]
    corpus_path: Path
    dataset_path: Path
    documents: dict[str, dict[str, Any]]
    """Poisoned documents by ID: attack, targets, canary."""

    @property
    def suite_hash(self) -> str:
        return str(self.descriptor["suite_hash"])

    @property
    def targets(self) -> list[str]:
        return list(self.descriptor["parameters"]["targets"])

    def documents_for(self, query_id: str) -> list[str]:
        return sorted(d for d, info in self.documents.items() if query_id in info["targets"])


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_suite(path: str | Path) -> Suite:
    """The suite whose ``poison-suite.json`` is at ``path``, verified against its files."""
    descriptor_path = Path(path)
    try:
        descriptor = json.loads(descriptor_path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise PoisonRunError(f"Cannot read {path}: {exc.strerror or exc}") from exc
    except ValueError as exc:
        raise PoisonRunError(f"{path} is not JSON.") from exc
    if (
        not isinstance(descriptor, dict)
        or descriptor.get("format") != SUITE_FORMAT
        or descriptor.get("format_version") != SUITE_FORMAT_VERSION
    ):
        raise PoisonRunError(f"{path} is not a poison suite (poison-suite.json).")
    root = descriptor_path.parent
    for name, info in (descriptor.get("outputs") or {}).items():
        file = root / name
        if not file.is_file():
            raise PoisonRunError(f"{name} is missing beside {descriptor_path.name}.")
        if _sha(file) != info.get("sha256"):
            raise PoisonRunError(
                f"{name} does not match the hash recorded in the suite: it was changed after "
                "the suite was generated. Generate the suite again."
            )
    corpus_path, dataset_path = root / "poison-corpus.jsonl", root / "poison-dataset.jsonl"
    if not corpus_path.is_file() or not dataset_path.is_file():
        raise PoisonRunError("The suite lacks poison-corpus.jsonl or poison-dataset.jsonl.")
    recomputed = hashlib.sha256(
        json.dumps(
            {
                "inputs": descriptor["inputs"],
                "parameters": descriptor["parameters"],
                "corpus": _sha(corpus_path),
            },
            sort_keys=True,
        ).encode()
    ).hexdigest()[:12]
    if recomputed != descriptor.get("suite_hash"):
        raise PoisonRunError("The suite hash does not match its parameters and corpus.")
    header = (load_dataset(dataset_path).meta.get("provenance") or {}).get("poison_suite")
    if header != recomputed:
        raise PoisonRunError("poison-dataset.jsonl was not generated by this suite.")
    documents = {
        d["doc_id"]: {"attack": d["attack"], "targets": d["targets"], "canary": d["canary"]}
        for d in descriptor["documents"]
    }
    return Suite(root, descriptor, corpus_path, dataset_path, documents)


def poisoned_side_problem(candidate: Candidate) -> str | None:
    """Why this candidate may not be the poisoned side of a run, or ``None`` if it may.

    The hybrid baseline needs a ``corpus_overlay``. Any other pipeline must declare
    ``"environment": "staging"`` and an ``overlay``: Vectraudit never inserts documents, so
    the poisoned index has to be yours, and it has to say it is not production.
    """
    if candidate.adapter.kind == "hybrid":
        if candidate.adapter.corpus_overlay is None:
            return (
                f"{candidate.name!r} is a hybrid candidate without adapter.corpus_overlay; "
                "point it at the suite's poison-corpus.jsonl"
            )
        return None
    missing = [
        field
        for field, value in (("environment", candidate.environment), ("overlay", candidate.overlay))
        if value is None
    ]
    if missing:
        return (
            f"{candidate.name!r} declares no {' or '.join(missing)}. Load the suite's documents "
            'into a staging index yourself, then declare "environment": "staging" and '
            '"overlay": "<path to poison-suite.json>" on the candidate. Vectraudit never '
            "writes to your backend."
        )
    return None


def overlay_visibility(run: Mapping[str, Any], suite: Suite) -> dict[str, Any]:
    """Whether any poisoned document appears in any recorded stage of any target question.

    A ``warning`` is set when none does: the overlay may not have been loaded into what was
    run (or nothing ranked, which looks identical). With no stage traces recorded, only the
    delivered results can be read, and the report says so.
    """
    entries = {e["query_id"]: e for e in run.get("queries") or []}
    targets = [q for q in suite.targets if q in entries and not entries[q].get("error")]
    seen: dict[str, list[str]] = {}
    traced = 0
    for qid in targets:
        entry = entries[qid]
        poisoned = set(suite.documents_for(qid))
        stages = (entry.get("evidence") or {}).get("stages") or []
        traced += bool(stages)
        found = {h["id"] for s in stages for h in s.get("hits") or []} & poisoned
        found |= set(entry.get("ids") or []) & poisoned
        if found:
            seen[qid] = sorted(found)
    result: dict[str, Any] = {
        "targets_in_run": len(targets),
        "targets_with_stage_traces": traced,
        "targets_where_a_poisoned_document_appeared": len(seen),
        "documents_seen": sorted({d for docs in seen.values() for d in docs}),
        "warning": None,
    }
    if targets and not seen:
        result["warning"] = (
            f"No poisoned document appears in any recorded "
            f"{'stage' if traced else 'result'} for the {len(targets)} target questions: the "
            "overlay may not be loaded into the pipeline that was run. This is a warning, not "
            "proof: a poisoned document that ranks nowhere looks the same."
            + (
                ""
                if traced
                else " No stage traces were recorded, so only delivered results were read."
            )
        )
    return result
